# My birthday is December 14,2002. In this scenario, the length of the rectangle would be the day of 
# my birthday since it is numerically larger, and the month would be the width because it is smaller. 
# So the dimensions of the rectangle are: length is 14 with a width of 12.

# 1. Assign variables
length = 14
width = 12 

# 2. Calculate the area
# Area is calculated by multiplying the width with the length
area = width * length

# 3. Display the result 
print(f'Side A is {length}')
print(f'Side B is {width}')
print(f'The area of the rectangle is {area}')

